using Microsoft.Build.Framework;
using Microsoft.Build.Utilities;
using SkiaSharp;
using System;
using System.Globalization;
using System.IO;
using System.Xml;
using System.Xml.Linq;

namespace Uno.Resizetizer
{
	/// <summary>
	/// Generates Resources/values/uno_colors.xml and Resources/drawable/uno_splash_image.xml for Android splash screens
	/// </summary>
	public class GenerateSplashAndroidResources_v0 : Task, ILogger
	{
		[Required]
		public string IntermediateOutputPath { get; set; }

		[Required]
		public ITaskItem[] UnoSplashScreen { get; set; }

		public override bool Execute()
		{
#if DEBUG_RESIZETIZER
			//System.Diagnostics.Debugger.Launch();
#endif
			var splash = UnoSplashScreen[0];

			var info = ResizeImageInfo.ParseSplashScreen(splash);

			var tools = SkiaSharpTools.Create(info.IsVector, info.Filename, info.BaseSize, info.Color, info.TintColor, this);

			WriteXmlIfChanged("values", "uno_colors.xml", writer => WriteColors(writer, info));
			WriteXmlIfChanged("drawable", "uno_splash_image.xml", writer => WriteDrawable(writer, info));
			WriteXmlIfChanged("drawable-v31", "uno_splash_image.xml", writer => WriteDrawable_v31(writer, info, tools));

			return !Log.HasLoggedErrors;
		}

		static readonly XmlWriterSettings Settings = new XmlWriterSettings { Indent = true };
		const string Namespace = "http://schemas.android.com/apk/res/android";
		const string Comment = "This file was auto-generated by Uno Platform.";
		const float PreferredImageSize = 108f;

		// These files are Android resources: rewriting them with the same content still bumps their timestamp,
		// which makes aapt2 recompile them and the APK get repackaged and fully reinstalled on every build.
		// The XML is compared rather than the text, because the Android SDK's _ConvertResourcesCases rewrites
		// them in place without the declaration and the indentation.
		void WriteXmlIfChanged(string resourceDirectory, string fileName, Action<XmlWriter> write)
		{
			var directory = Path.Combine(IntermediateOutputPath, resourceDirectory);
			var file = Path.Combine(directory, fileName);

			using var content = new MemoryStream();
			using (var writer = XmlWriter.Create(content, Settings))
			{
				write(writer);
			}

			if (File.Exists(file))
			{
				content.Position = 0;
				if (IsSameXml(file, XDocument.Load(content)))
				{
					Log.LogMessage(MessageImportance.Low, $"Skipping unchanged {file}");
					return;
				}
			}

			Directory.CreateDirectory(directory);
			File.WriteAllBytes(file, content.ToArray());
		}

		static bool IsSameXml(string file, XDocument expected)
		{
			try
			{
				return XNode.DeepEquals(XDocument.Load(file), expected);
			}
			catch (XmlException)
			{
				return false;
			}
		}

		static void WriteColors(XmlWriter writer, ResizeImageInfo splash)
		{
			writer.WriteComment(Comment);
			writer.WriteStartElement("resources");

			writer.WriteStartElement("color");
			writer.WriteAttributeString("name", "uno_splash_color");
			writer.WriteString(splash.Color?.ToString() ?? "#00000000");
			writer.WriteEndElement();

			writer.WriteEndDocument();
		}

		static void WriteDrawable(XmlWriter writer, ResizeImageInfo splash)
		{
			writer.WriteComment(Comment);
			writer.WriteStartElement("layer-list");
			writer.WriteAttributeString("xmlns", "android", ns: null, value: Namespace);

			writer.WriteStartElement("item");
			writer.WriteStartElement("color");
			writer.WriteAttributeString("android", "color", Namespace, "@color/uno_splash_color");
			writer.WriteEndElement();
			writer.WriteFullEndElement();

			writer.WriteStartElement("item");
			writer.WriteStartElement("bitmap");
			writer.WriteAttributeString("android", "gravity", Namespace, "center");
			writer.WriteAttributeString("android", "src", Namespace, "@drawable/" + Utils.ToAndroidDrawableName(splash.OutputName));
			writer.WriteAttributeString("android", "tileMode", Namespace, "disabled");
			writer.WriteAttributeString("android", "mipMap", Namespace, "true");
			writer.WriteEndDocument();
		}

		static void WriteDrawable_v31(XmlWriter writer, ResizeImageInfo splash, SkiaSharpTools tools)
		{
			var size = CalculateScaledSize(tools);

			writer.WriteComment(Comment);
			writer.WriteStartElement("layer-list");
			writer.WriteAttributeString("xmlns", "android", ns: null, value: Namespace);

			writer.WriteStartElement("item");
			writer.WriteStartElement("color");
			writer.WriteAttributeString("android", "color", Namespace, "@color/uno_splash_color");
			writer.WriteEndElement();
			writer.WriteFullEndElement();

			writer.WriteStartElement("item");
			writer.WriteAttributeString("android", "width", Namespace, size.Width.ToString("0", CultureInfo.InvariantCulture) + "dp");
			writer.WriteAttributeString("android", "height", Namespace, size.Height.ToString("0", CultureInfo.InvariantCulture) + "dp");
			writer.WriteAttributeString("android", "gravity", Namespace, "center");

			writer.WriteStartElement("bitmap");
			writer.WriteAttributeString("android", "gravity", Namespace, "fill");
			writer.WriteAttributeString("android", "src", Namespace, "@drawable/" + Utils.ToAndroidDrawableName(splash.OutputName));
			writer.WriteAttributeString("android", "mipMap", Namespace, "true");
			writer.WriteAttributeString("android", "tileMode", Namespace, "disabled");

			writer.WriteEndDocument();
		}

		void ILogger.Log(string message)
		{
			Log?.LogMessage(message);
		}

		static SKSize CalculateScaledSize(SkiaSharpTools tools)
		{
			var size = tools.BaseSize ?? tools.GetOriginalSize();

			var width = PreferredImageSize;
			var height = PreferredImageSize;

			if (size.Width > size.Height)
			{
				height = size.Height / size.Width * width;
			}
			else
			{
				width = size.Width / size.Height * height;
			}

			return new SKSize(width, height);
		}
	}
}
