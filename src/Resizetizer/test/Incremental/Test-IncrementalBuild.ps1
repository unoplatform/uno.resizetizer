<#
.SYNOPSIS
	Runs a no-change rebuild of an already built app and fails if it rewrote anything Uno.Resizetizer generates.

.DESCRIPTION
	Guards https://github.com/unoplatform/uno.resizetizer/issues/293: a generated file rewritten with the same
	content still gets a newer timestamp, and everything downstream treats it as changed. On Android this
	recompiles the resources and repackages, re-signs and fully reinstalls the APK on every build.

	The script snapshots every file under obj/**/unoresizetizer/ in the app directory: the resized images,
	splash screen resources, icons and manifests, and on Android the aapt2 .flat files compiled from them.
	It then runs `dotnet build` with the given arguments, and fails if any of them was rewritten, created
	or deleted.

	It also fails if an app assembly no longer embeds UnoSplash.def, the splash screen definition read by the
	Toolkit's ExtendedSplashScreen: skipping the splash screen targets wholesale on an incremental build drops it.

	Rewritten APKs are only reported: the Android SDK can repackage for reasons of its own, such as adb.props
	being written on the first build after a clean one.

	The app must have been built with the same arguments right before, so that nothing is left to do.

.EXAMPLE
	./Test-IncrementalBuild.ps1 -AppDirectory samples/7.0/Uno52ResizetizerTests/Uno52ResizetizerTests -BuildArguments samples/7.0/Uno52ResizetizerTests/Uno52ResizetizerTests.sln, -c, Debug
#>
param(
	[Parameter(Mandatory)]
	[string] $AppDirectory,

	[Parameter(Mandatory)]
	[string[]] $BuildArguments
)

$ErrorActionPreference = 'Stop'

$AppDirectory = (Resolve-Path $AppDirectory).Path
$appName = Split-Path $AppDirectory -Leaf

function Get-Snapshot([string] $Directory, [scriptblock] $Filter) {
	$snapshot = @{}
	Get-ChildItem -Path (Join-Path $AppDirectory $Directory) -Recurse -File -ErrorAction SilentlyContinue |
		Where-Object $Filter |
		ForEach-Object { $snapshot[$_.FullName] = $_.LastWriteTimeUtc }
	return $snapshot
}

function Compare-Snapshot([hashtable] $Before, [hashtable] $After) {
	foreach ($path in $Before.Keys | Sort-Object) {
		if (-not $After.ContainsKey($path)) {
			"Deleted:   $path"
		}
		elseif ($After[$path] -ne $Before[$path]) {
			"Rewritten: $path"
		}
	}
	foreach ($path in $After.Keys | Sort-Object) {
		if (-not $Before.ContainsKey($path)) {
			"Created:   $path"
		}
	}
}

$generated = { $_.FullName -match '[\\/]unoresizetizer[\\/]' }
$apks = { $_.Extension -eq '.apk' }

$generatedBefore = Get-Snapshot 'obj' $generated
$apksBefore = Get-Snapshot 'bin' $apks
if ($generatedBefore.Count -eq 0) {
	throw "Nothing generated by Uno.Resizetizer was found under '$AppDirectory'. Build the app before running this script."
}
Write-Host "Tracking $($generatedBefore.Count) generated files under '$AppDirectory'."

& dotnet build @BuildArguments
if ($LASTEXITCODE -ne 0) {
	throw "The incremental build failed with exit code $LASTEXITCODE."
}

$failures = @(Compare-Snapshot $generatedBefore (Get-Snapshot 'obj' $generated))
$apkChanges = @(Compare-Snapshot $apksBefore (Get-Snapshot 'bin' $apks))

# UnoSplash.def sits next to the app assembly in the intermediate directory that compiles it
foreach ($definition in Get-ChildItem -Path (Join-Path $AppDirectory 'obj') -Recurse -File -Filter 'UnoSplash.def') {
	$assembly = Join-Path $definition.DirectoryName "$appName.dll"
	if (-not (Test-Path $assembly)) {
		continue
	}

	# Manifest resource names are stored as UTF-8 in the metadata string heap
	$content = [System.Text.Encoding]::UTF8.GetString([System.IO.File]::ReadAllBytes($assembly))
	if ($content.Contains('UnoSplash.def')) {
		Write-Host "UnoSplash.def is embedded in $assembly"
	}
	else {
		$failures += "Missing UnoSplash.def resource: $assembly"
	}
}

if ($apkChanges.Count -gt 0) {
	Write-Host ''
	Write-Host 'The incremental build repackaged the APK:'
	$apkChanges | ForEach-Object { Write-Host "  $_" }
	if ($env:GITHUB_ACTIONS -eq 'true') {
		Write-Host '::warning title=Incremental build::The APK was repackaged on a no-change rebuild, see the log for the reason.'
	}
}

if ($failures.Count -gt 0) {
	Write-Host ''
	Write-Host 'The incremental build was not a no-op for Uno.Resizetizer (https://github.com/unoplatform/uno.resizetizer/issues/293):'
	$failures | ForEach-Object { Write-Host "  $_" }
	if ($env:GITHUB_ACTIONS -eq 'true') {
		Write-Host "::error title=Incremental build::$($failures.Count) Uno.Resizetizer output(s) changed on a no-change rebuild, see the log above."
	}
	exit 1
}

Write-Host ''
Write-Host "The incremental build left all $($generatedBefore.Count) generated files untouched."
